/**
 * A fixed-date entry of the calendar.
 * cls 1–3 = class of the feast; cls 0 = commemoration only (no office of its own).
 * [comm] = saints commemorated at Lauds on this day.
 * [carm] = the Carmelite proper for this day, shown when that option is on.
 */
